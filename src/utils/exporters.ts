/**
 * Export and Clipboard Utilities for Test Cases, Bug Reports, and Playwright Scripts
 */

import { TestCase, BugAnalysisItem } from '../types';

export function downloadFile(
  content: string,
  filename: string,
  mimeType: string
): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

export function exportTestCasesToJson(testCases: TestCase[]): void {
  const jsonContent = JSON.stringify(testCases, null, 2);
  const filename = `testcases-${new Date().toISOString().slice(0, 10)}.json`;
  downloadFile(jsonContent, filename, 'application/json');
}

export function exportTestCasesToCsv(testCases: TestCase[]): void {
  const headers = [
    'ID',
    'Title',
    'Category',
    'Priority',
    'Status',
    'Target Browser',
    'Objective',
    'Preconditions',
    'Steps',
    'Test Data',
    'Expected Result',
    'Execution Notes',
    'Generated By',
  ];

  const escapeCsv = (val: string | string[] | undefined): string => {
    if (val === undefined || val === null) return '""';
    const str = Array.isArray(val) ? val.join('; ') : String(val);
    const escaped = str.replace(/"/g, '""');
    return `"${escaped}"`;
  };

  const rows = testCases.map((tc) => [
    escapeCsv(tc.id),
    escapeCsv(tc.title),
    escapeCsv(tc.category),
    escapeCsv(tc.priority),
    escapeCsv(tc.status),
    escapeCsv(tc.targetBrowser),
    escapeCsv(tc.objective),
    escapeCsv(tc.preconditions),
    escapeCsv(tc.steps),
    escapeCsv(tc.testData),
    escapeCsv(tc.expectedResult),
    escapeCsv(tc.executionNotes || ''),
    escapeCsv(tc.generatedBy),
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join(
    '\r\n'
  );

  const filename = `testcases-${new Date().toISOString().slice(0, 10)}.csv`;
  downloadFile(csvContent, filename, 'text/csv;charset=utf-8;');
}

export function exportBugsToJson(bugs: BugAnalysisItem[]): void {
  const jsonContent = JSON.stringify(bugs, null, 2);
  const filename = `bug-analysis-${new Date().toISOString().slice(0, 10)}.json`;
  downloadFile(jsonContent, filename, 'application/json');
}

export function exportBugsToMarkdown(bugs: BugAnalysisItem[]): void {
  let md = `# Static Bug & Failure Mode Analysis Report\n`;
  md += `*Generated by TestGenius AI on ${new Date().toUTCString()}*\n\n`;
  md += `> **Notice**: These potential issues are inferred from heuristic static inspection. No code execution or live server penetration was performed.\n\n`;

  bugs.forEach((bug, index) => {
    md += `## ${index + 1}. [${bug.severity}] ${bug.title}\n`;
    md += `- **ID**: \`${bug.id}\`\n`;
    md += `- **Category**: ${bug.category}\n`;
    md += `- **Affected Feature**: ${bug.affectedFeature}\n\n`;
    md += `### Explanation\n${bug.explanation}\n\n`;
    md += `### Reproduction Steps\n`;
    bug.reproductionSteps.forEach((s, i) => {
      md += `${i + 1}. ${s}\n`;
    });
    md += `\n### Expected vs Actual\n`;
    md += `- **Expected**: ${bug.expectedBehavior}\n`;
    md += `- **Actual**: ${bug.actualBehavior}\n\n`;
    md += `### Suggested Fix\n${bug.suggestedFix}\n\n`;
    if (bug.suggestedCodeSnippet) {
      md += `\`\`\`html\n${bug.suggestedCodeSnippet}\n\`\`\`\n\n`;
    }
    md += `---\n\n`;
  });

  const filename = `bug-analysis-${new Date().toISOString().slice(0, 10)}.md`;
  downloadFile(md, filename, 'text/markdown');
}

export function downloadPythonScript(pythonCode: string, filename = 'test_suite.py'): void {
  downloadFile(pythonCode, filename, 'text/x-python');
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch (err) {
    console.warn('Clipboard writeText failed, using fallback:', err);
  }

  try {
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textarea);
    return successful;
  } catch {
    return false;
  }
}
